#!/usr/bin/env node
// Copies the landing-page scenes from the design system (UX owns the originals in
// docs/design/assets/Illustrations) into src/assets/illustrations and writes
// src/components/parallax/scenes.generated.ts from layers/manifest.json (order, depth, axis).
// Run after UX changes a scene: `pnpm scenes`. The output is committed, so builds don't need docs/.
// A unit test (scenes.test.ts) fails when the copies drift from the design system.
/* global process, console */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SRC_DIR = join(web, "..", "..", "docs", "design", "assets", "Illustrations");
export const OUT_DIR = join(web, "src", "assets", "illustrations");
export const GEN_FILE = join(web, "src", "components", "parallax", "scenes.generated.ts");

// Scene id → flat fallback files (no-JS and reduced motion) + manifest keys for the layers.
export const SCENES = {
  village: { flat: { day: "scene-village-hero-day.svg", night: "scene-village-night.svg" } },
  city: { flat: { day: "scene-city-hero-day.svg", night: "scene-city-night.svg" } },
  highway: { flat: { day: "scene-highway-wide-day.svg", night: "scene-highway-wide-night.svg" } },
  canal: { flat: { day: "scene-canal-wide-day.svg", night: "scene-canal-wide-night.svg" } },
};

export function plan() {
  const manifest = JSON.parse(readFileSync(join(SRC_DIR, "layers", "manifest.json"), "utf8"));
  const scenes = {};
  for (const [id, s] of Object.entries(SCENES)) {
    scenes[id] = {};
    for (const mode of ["day", "night"]) {
      const m = manifest.scenes[`${id}-${mode}`];
      if (!m) throw new Error(`manifest.json has no scene ${id}-${mode}`);
      scenes[id][mode] = {
        flat: s.flat[mode],
        axis: m.axis,
        viewBox: m.viewBox,
        layers: m.layers.map((l) => ({ file: l.file, depth: l.speed ?? l.depth })),
      };
    }
  }
  return { manifest, scenes };
}

function ident(file) {
  return file.replace(/^layers\//, "L_").replace(/\.svg$/, "").replace(/[^A-Za-z0-9]/g, "_");
}

export function generate({ manifest, scenes }) {
  const imports = [];
  const body = [];
  for (const [id, modes] of Object.entries(scenes)) {
    // One export per scene, so a page only bundles the scenes it imports.
    body.push(`export const ${id}: SceneSet = {`);
    for (const [mode, s] of Object.entries(modes)) {
      for (const f of [s.flat, ...s.layers.map((l) => l.file)]) {
        const line = `import ${ident(f)} from "@/assets/illustrations/${f}";`;
        if (!imports.includes(line)) imports.push(line);
      }
      const layers = s.layers.map((l) => `{ img: ${ident(l.file)}, depth: ${l.depth} }`).join(", ");
      body.push(`  ${mode}: { axis: "${s.axis}", viewBox: "${s.viewBox}", flat: ${ident(s.flat)}, layers: [${layers}] },`);
    }
    body.push("};", "");
  }
  return [
    "// GENERATED by scripts/scenes.mjs from docs/design/assets/Illustrations/layers/manifest.json. Do not edit.",
    'import type { SceneSet } from "./types";',
    ...imports,
    "",
    `export const PARALLAX = { amp: ${manifest.amp_px}, tilt: ${manifest.tilt_px}, drive: ${manifest.drive_px} } as const;`,
    "",
    ...body,
  ].join("\n");
}

function main() {
  const p = plan();
  rmSync(join(OUT_DIR, "layers"), { recursive: true, force: true });
  mkdirSync(join(OUT_DIR, "layers"), { recursive: true });
  for (const modes of Object.values(p.scenes)) {
    for (const s of Object.values(modes)) {
      for (const f of [s.flat, ...s.layers.map((l) => l.file)]) copyFileSync(join(SRC_DIR, f), join(OUT_DIR, f));
    }
  }
  mkdirSync(dirname(GEN_FILE), { recursive: true });
  writeFileSync(GEN_FILE, generate(p));
  console.log(`scenes: ${readdirSync(join(OUT_DIR, "layers")).length} layers, ${Object.keys(p.scenes).length} scenes`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
