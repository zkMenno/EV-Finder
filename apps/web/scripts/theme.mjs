// Design tokens → CSS custom properties (design system v2 from the UX chat, docs/design/tokens.json).
// Writes src/app/tokens.generated.css: the colour tokens for the light theme "Day trip" (:root) and
// the dark theme "Night drive" ([data-theme="dark"], and prefers-color-scheme: dark unless the
// visitor picked light), plus shadows. App code reads them as var(--ink) etc.; globals.css maps
// Tailwind's palette onto them, so existing classes follow the theme.
//
//   node scripts/theme.mjs           write the CSS (runs before `next build` and `next dev`)
//   node scripts/theme.mjs --check   fail if the committed CSS is out of date
// docs/ is not in the Docker build context: then the committed CSS is kept (same as sources.mjs).
/* global process, console */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOKENS_FILE = path.resolve(here, "../../../docs/design/tokens.json");
export const OUT_FILE = path.resolve(here, "../src/app/tokens.generated.css");
const NAME = /^[a-z][a-z0-9-]*$/;
const VALUE = /^[#(),.\s\w%-]+$/;

/** One theme's values: name → value, with "{other}" references resolved. */
function themeValues(tokens, theme) {
  const raw = new Map(tokens.map((t) => [t.name, t.value?.[theme]]));
  const resolve = (name, seen = new Set()) => {
    const v = raw.get(name);
    if (typeof v !== "string") throw new Error(`tokens.json: ${name} has no ${theme} value`);
    const ref = v.match(/^\{([a-z0-9-]+)\}$/);
    if (!ref) return v;
    if (seen.has(name)) throw new Error(`tokens.json: reference loop at ${name}`);
    return resolve(ref[1], new Set([...seen, name]));
  };
  return tokens.map((t) => {
    if (!NAME.test(t.name)) throw new Error(`tokens.json: bad token name ${t.name}`);
    const v = resolve(t.name);
    if (!VALUE.test(v)) throw new Error(`tokens.json: bad value for ${t.name}: ${v}`);
    return [t.name, v];
  });
}

export function buildCss(doc) {
  const colors = doc?.color?.tokens;
  if (!Array.isArray(colors)) throw new Error("tokens.json: expected color.tokens");
  const shadows = Array.isArray(doc?.shadow?.tokens) ? doc.shadow.tokens : [];
  const all = [...colors, ...shadows];
  const block = (theme) => themeValues(all, theme).map(([n, v]) => `  --${n}: ${v};`).join("\n");
  const names = Object.fromEntries((doc.color.themes ?? []).map((t) => [t.id, t.name]));
  const light = block("light");
  const dark = block("dark");
  return `/* Generated by scripts/theme.mjs from docs/design/tokens.json (${doc.name ?? "tokens"} v${doc.version ?? "?"}). Do not edit. */
/* Light: "${names.light ?? "light"}". Dark: "${names.dark ?? "dark"}". */
:root {
  color-scheme: light;
${light}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${dark}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.replace(/^/gm, "  ")}
  }
}

/* Paper is paper: print always uses the light theme. */
@media print {
  :root,
  :root[data-theme] {
    color-scheme: light;
${light.replace(/^/gm, "  ")}
  }
}
`;
}

export function loadCss(file = TOKENS_FILE) {
  return buildCss(JSON.parse(readFileSync(file, "utf8")));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (!existsSync(TOKENS_FILE)) {
    console.log(`theme: ${path.relative(process.cwd(), TOKENS_FILE)} not found, keeping the committed CSS`);
    process.exit(0);
  }
  const css = loadCss();
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";
    if (cur !== css) {
      console.error("theme: src/app/tokens.generated.css is stale; run `pnpm theme`");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT_FILE, css);
    console.log(`theme: wrote ${path.relative(process.cwd(), OUT_FILE)}`);
  }
}
